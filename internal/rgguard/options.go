package rgguard

// role is what one ripgrep option word does to an rg call.
type role uint8

const (
	// flag takes no value.
	flag role = iota
	// valued takes one value.
	valued
	// pattern takes a pattern, so every positional is a path.
	pattern
	// patternFile takes a file of patterns, so every positional is a path. The value `-`
	// reads the patterns from stdin.
	patternFile
	// mode needs no pattern and no path.
	mode
	// valuedMode is a mode that takes one value.
	valuedMode
)

// takesValue reports whether an option word consumes a value.
func (r role) takesValue() bool { return r != flag && r != mode }

