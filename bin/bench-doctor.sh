#!/usr/bin/env bash
# shellcheck shell=bash
# bench doctor [--fix] — shim health for a node-version-manager global install.
#
# A global `npm install -g benchkit` under nvm/asdf/fnm/volta drops the `bench`
# executable only into the manager's version-specific bin, which login shells and
# `bash -c "bench ..."` do not have on PATH. This subcommand reports that (report
# mode) and repairs it (--fix) by writing a plain-shell wrapper into the first
# writable PATH dir outside manager-owned territory, so every shell resolves bench.
#
# It is the deep unit: it hides platform and version-manager variance (probe order,
# the manager exclusion list, shell detection) behind a report/fix interface, and
# runs with no `bench` on PATH and no GNU `readlink -f` — that is the premise. It
# resolves the running CLI's real path with resolve_script_path (bin/bench.sh),
# never `readlink -f`. Sourced by bin/bench.sh; postinstall, the generated wrapper,
# and the session-start advisory are thin pass-throughs with no seam of their own.
#
# One source per fact: the marker substring, the wrapper template, and the target-dir
# selection each have exactly one home here.

# The marker that identifies a Bench-written shim. Detection matches the stable ID
# substring; the full comment line embeds it, so the two never drift.
BENCH_SHIM_MARKER_ID='bench-shim v1'
BENCH_SHIM_MARKER="# $BENCH_SHIM_MARKER_ID — generated by bench doctor --fix; do not hand-edit"

# _under DIR PREFIX — true when DIR is PREFIX itself or lives under PREFIX/.
doctor_under() {
  case "$1/" in "$2/"*) return 0 ;; esac
  return 1
}

# Manager-owned dirs are writable-but-wrong: a shim there rides the same
# version-specific / package-manager tree the feature exists to escape. Covers
# version-manager trees, Homebrew prefixes, and system prefixes.
doctor_manager_owned() {
  local d="$1" p
  for p in \
    "${NVM_DIR:-$HOME/.nvm}" \
    "${ASDF_DATA_DIR:-$HOME/.asdf}" \
    "${FNM_DIR:-}" "$HOME/.local/share/fnm" "$HOME/.fnm" \
    "${VOLTA_HOME:-$HOME/.volta}" \
    "${HOMEBREW_PREFIX:-}" /opt/homebrew /usr/local \
    /usr /bin /sbin /opt
  do
    [ -n "$p" ] || continue
    doctor_under "$d" "$p" && return 0
  done
  return 1
}

# Chosen target dir + whether --fix must create it. First writable PATH dir that is
# not manager-owned; else ~/.local/bin as the fallback (created only when absent).
DOCTOR_DIR=""
DOCTOR_CREATED=0
doctor_select_dir() {
  local dir
  DOCTOR_DIR=""
  DOCTOR_CREATED=0
  local IFS=:
  for dir in $PATH; do
    [ -n "$dir" ] || continue
    [ -d "$dir" ] || continue
    [ -w "$dir" ] || continue
    doctor_manager_owned "$dir" && continue
    DOCTOR_DIR="$dir"
    return 0
  done
  DOCTOR_DIR="$HOME/.local/bin"
  [ -d "$DOCTOR_DIR" ] || DOCTOR_CREATED=1
  return 0
}

doctor_dir_on_path() {
  case ":$PATH:" in *":$1:"*) return 0 ;; esac
  return 1
}

doctor_has_marker() {
  grep -qF "$BENCH_SHIM_MARKER_ID" "$1" 2>/dev/null
}

# The generated wrapper: a static exec of the CLI's own resolved real path, captured
# at fix time. A missing target (a version-manager move relocated the package) fails
# loud rather than silently running a stale copy. %q keeps a spaced or glob target
# intact; "$@" preserves multi-word and glob args verbatim.
doctor_shim_content() {
  local target q
  q="$(printf '%q' "$1")"
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    "$BENCH_SHIM_MARKER" \
    "target=$q" \
    'if [ ! -x "$target" ]; then' \
    "  printf 'bench moved — run '\''bench doctor --fix'\'' or reinstall\\n' >&2" \
    '  exit 127' \
    'fi' \
    'exec "$target" "$@"'
}

# Read the target= line back out of an existing shim, reversing the %q quoting in a
# subshell so the caller's variables are untouched.
doctor_shim_target() {
  ( eval "$(grep -m1 '^target=' "$1" 2>/dev/null)"; printf '%s' "${target:-}" )
}

# Print the exact one-line PATH addition for the user's shell when the chosen dir is
# off PATH (the fallback). rc files are never edited — the user pastes.
doctor_path_notice() {
  doctor_dir_on_path "$DOCTOR_DIR" && return 0
  echo "  note: $DOCTOR_DIR is not on PATH — add it, then restart your shell:"
  case "$(basename "${SHELL:-/bin/sh}")" in
    fish) echo "    fish_add_path $DOCTOR_DIR" ;;
    *)    echo "    export PATH=\"$DOCTOR_DIR:\$PATH\"" ;;
  esac
}

# Report shim health, mutating nothing. Exit 0 only when healthy; 1 for
# missing/stale/foreign. Always prints the machine-exact fix and removal lines.
doctor_report() {
  local target found="" shim_path state rc d t
  target="$(resolve_script_path)"
  doctor_select_dir
  local target_path="$DOCTOR_DIR/bench"
  local IFS=:
  for d in $PATH; do
    [ -n "$d" ] || continue
    if [ -f "$d/bench" ] && doctor_has_marker "$d/bench"; then found="$d/bench"; break; fi
  done
  unset IFS
  if [ -n "$found" ]; then
    shim_path="$found"
    t="$(doctor_shim_target "$found")"
    if [ -n "$t" ] && [ -x "$t" ]; then state=healthy; else state=stale; fi
  elif [ -e "$target_path" ]; then
    shim_path="$target_path"; state=foreign
  else
    shim_path="$target_path"; state=missing
  fi
  echo "bench doctor — shim health"
  case "$state" in
    healthy) echo "  ok: healthy bench shim at $shim_path"; rc=0 ;;
    stale)   echo "  stale: shim at $shim_path points to a missing target (version-manager move?)"; rc=1 ;;
    foreign) echo "  foreign: $shim_path exists but is not a bench shim (no marker)"; rc=1 ;;
    missing) echo "  missing: no bench shim on a stable PATH dir"; rc=1 ;;
  esac
  echo "  fix:    bench doctor --fix"
  echo "  remove: npm uninstall -g benchkit && rm -f \"$shim_path\""
  return "$rc"
}

# Write the shim, announcing every mutation with its absolute path. Idempotent over
# an already-current shim; refuses a foreign (marker-less) file, leaving it
# byte-identical. Atomic: temp file in the target dir then mv, so a SIGINT leaves
# either the old state or the whole new shim, never a partial file.
doctor_fix() {
  local target target_path content tmp
  target="$(resolve_script_path)"
  doctor_select_dir
  if [ "$DOCTOR_CREATED" = 1 ]; then
    mkdir -p "$DOCTOR_DIR" || { echo "  error: could not create $DOCTOR_DIR" >&2; return 1; }
    echo "  created directory $DOCTOR_DIR"
  fi
  target_path="$DOCTOR_DIR/bench"
  content="$(doctor_shim_content "$target")"
  if [ -e "$target_path" ]; then
    if doctor_has_marker "$target_path"; then
      if [ "$(cat "$target_path")" = "$content" ]; then
        echo "  ok: shim already current at $target_path (no change)"
        doctor_path_notice
        return 0
      fi
    else
      echo "  refusing: $target_path exists and is not a bench shim (no marker); left unchanged" >&2
      return 1
    fi
  fi
  tmp="$(mktemp "$DOCTOR_DIR/.bench-shim.XXXXXX")" || { echo "  error: cannot write in $DOCTOR_DIR" >&2; return 1; }
  printf '%s\n' "$content" > "$tmp"
  chmod 0755 "$tmp"
  mv -f "$tmp" "$target_path"
  echo "  wrote shim $target_path (exec -> $target)"
  doctor_path_notice
  return 0
}

doctor() {
  case "${1:-}" in
    --fix) doctor_fix ;;
    "")    doctor_report ;;
    *)     echo "usage: bench doctor [--fix]" >&2; return 2 ;;
  esac
}
